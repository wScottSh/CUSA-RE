#!/usr/bin/env python3
"""Name library functions by matching n64sym signatures against every code segment.

Reads an n64sym .sig file as data (format: n64sym/signature-file-format.md) and
reimplements its matcher: at each likely function start, zero the relocated
fields, then compare CRC32 of the first 8 bytes and of the whole function.
A match also names the targets of its jal relocations that point at named
functions. Output is splat symbol_addrs lines for symbols.lib.txt.

usage: libsigs.py SIGFILE > symbols.lib.txt
"""
import re
import sys
import zlib
from dataclasses import dataclass, field

from layout import ROM_PATH, Segment, load_layout

FIELD_MASK = {".hi16": 0xFFFF0000, ".lo16": 0xFFFF0000, ".targ26": 0xFC000000}
MIN_SIZE = 0x30
LOCAL = re.compile(r"_(text|data|rodata|bss)_[0-9A-F]{4}$")


@dataclass
class Sig:
    name: str
    size: int
    crc_a: int
    crc_b: int
    relocs: list[tuple[str, str, int]] = field(default_factory=list)


def parse_sigs(text: str) -> list[Sig]:
    sigs: list[Sig] = []
    for line in text.splitlines():
        parts = line.split()
        if not parts or parts[0].startswith("#"):
            continue
        if parts[0].startswith("."):
            sigs[-1].relocs += [(parts[0], parts[1], int(o, 0)) for o in parts[2:]]
        else:
            sigs.append(Sig(parts[0], int(parts[1], 0), int(parts[2], 0), int(parts[3], 0)))
    return sigs


def masked(code: bytes, sig: Sig) -> bytes:
    buf = bytearray(code)
    for kind, _, off in sig.relocs:
        word = int.from_bytes(buf[off:off + 4], "big") & FIELD_MASK[kind]
        buf[off:off + 4] = word.to_bytes(4, "big")
    return bytes(buf)


def candidates(code: bytes) -> list[int]:
    out = set()
    for i in range(0, len(code) - 12, 4):
        w = int.from_bytes(code[i:i + 4], "big")
        if w == 0x03E00008 and code[i + 8:i + 12] != b"\0\0\0\0":
            out.add(i + 8)
        if w >> 16 == 0x27BD and w & 0x8000:
            out.add(i)
    return sorted(out)


def head_mask(sig: Sig) -> tuple[tuple[str, int], ...]:
    return tuple(sorted((k, o) for k, _, o in sig.relocs if o < 8))


def scan(seg: Segment, rom: bytes, sigs: list[Sig]) -> list[tuple[int, str]]:
    """(vram, name) for every confident match and the named jal targets inside it."""
    code = rom[seg.rom_start:seg.rom_end]
    index: dict[tuple, dict[int, list[Sig]]] = {}
    for s in sigs:
        if s.size >= MIN_SIZE:
            index.setdefault(head_mask(s), {}).setdefault(s.crc_a, []).append(s)
    found = []
    for off in candidates(code):
        for mask, by_crc in index.items():
            head = masked(code[off:off + 8], Sig("", 8, 0, 0, [(k, "", o) for k, o in mask]))
            for sig in by_crc.get(zlib.crc32(head), []):
                if off + sig.size > len(code) or zlib.crc32(masked(code[off:off + sig.size], sig)) != sig.crc_b:
                    continue
                found.append((seg.vram + off, sig.name))
                for kind, target, roff in sig.relocs:
                    if kind == ".targ26" and not LOCAL.search(target):
                        w = int.from_bytes(code[off + roff:off + roff + 4], "big")
                        found.append(((seg.vram & 0xF0000000) | (w & 0x03FFFFFF) << 2, target))
    return found


def unambiguous(found: list[tuple[Segment, int, str]]) -> list[tuple[Segment, int, str]]:
    """Keep only names with one address and addresses with one name."""
    uniq = set(found)
    by_name, by_addr = {}, {}
    for seg, vram, name in uniq:
        by_name.setdefault(name, set()).add((seg.name, vram))
        by_addr.setdefault((seg.name, vram), set()).add(name)
    keep = []
    for seg, vram, name in sorted(uniq, key=lambda t: (t[0].rom_start, t[1])):
        if len(by_name[name]) > 1 or len(by_addr[(seg.name, vram)]) > 1:
            print(f"dropped {name} at {seg.name}:{vram:#x} (ambiguous)", file=sys.stderr)
        else:
            keep.append((seg, vram, name))
    return keep


def main() -> None:
    sigs = parse_sigs(open(sys.argv[1]).read())
    layout = load_layout()
    rom = ROM_PATH.read_bytes()
    print(f"// generated by tools/libsigs.py from {sys.argv[1].rsplit('/', 1)[-1]}; do not edit")
    found = []
    for seg in layout.segments:
        for vram, name in scan(seg, rom, sigs):
            target = seg if seg.rom_of(vram) is not None else next((r for r in layout.residents if r.rom_of(vram) is not None), None)
            if target is not None:
                found.append((target, vram, name))
    for seg, vram, name in unambiguous(found):
        attr = f" rom:0x{seg.rom_of(vram):X}" if seg.overlay else ""
        print(f"{name} = 0x{vram:08X}; // type:func{attr}")


if __name__ == "__main__":
    main()
